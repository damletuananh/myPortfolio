export function MvPixelLogo({
  className = "",
  secondary = false,
  animateFrames = false,
}: MvPixelLogoProps) {
  const [activeFrame, setActiveFrame] = useState(0);

  useEffect(() => {
    if (!animateFrames) {
      return;
    }

    let step = 0;
    const sequence = [0, 1, 2, 3, 0, 0, 0];
    const id = window.setInterval(() => {
      step = (step + 1) % sequence.length;
      setActiveFrame(sequence[step]);
    }, 180);

    return () => window.clearInterval(id);
  }, [animateFrames]);

  const displayedFrame = animateFrames ? activeFrame : 0;
  const accentFill = secondary ? "#D7C6AD" : "#F7A026";
  const bodyFill = secondary ? "#F7A026" : "currentColor";

  return (
    <svg
      viewBox="0 0 189 117"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={`MVLogo ${secondary ? "MVLogo--secondary" : ""} ${className}`.trim()}
      aria-label="Dam Le Tuan Anh — Vietnamese Grass Dog Pixel Emblem (Cún)"
      role="img"
    >
      {MV_PIXEL_FRAMES.map((frame, index) => (
        <g
          key={index}
          className={`MVLogo-${index + 1}`}
          style={{ opacity: displayedFrame === index ? 1 : 0 }}
        >
          <path className="mv-body" d={frame.body} fill={bodyFill} />
          <polygon className="mv-accent" points={frame.nose} fill={accentFill} />
          <polygon className="mv-accent" points={frame.chest} fill={accentFill} />
        </g>
      ))}
    </svg>
  );
}

